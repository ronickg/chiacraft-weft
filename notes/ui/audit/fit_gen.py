#!/usr/bin/env python3
"""Writes fit_all.txt: every screen and tab in every language and GUI scale, for the text-fit
check (`--ui-audit`, engine `ui::audit`). Run it with `-- --ui-audit` at each window size
(1280x720, 1920x1080, 3840x2160); `fit_report.py` turns the run.logs into the list.

In a world: the screens a name opens, the key screens (inventory, recipes, stats, advancements),
Multiplayer's Links and Friends. Then from the title: the title itself, Select World with its
delete and new-address questions, Create World, Multiplayer. The engine caps the GUI scale at what
the window holds, so 4x at 720p is checked as that cap.
"""
import pathlib

LANGS = ["en_us", "ru_ru", "fr_fr"]
SCALES = [0, 1, 2, 3, 4]  # 0: auto

# Opened by name in a world (core:loading, core:death, core:editor and the test mods' left out:
# a loading screen with nothing loading, a death that kills, the world editor's own tool).
IN_WORLD = [
    "core:pause", "core:settings", "core:video", "core:accessibility", "core:chat_settings",
    "core:sound", "core:language", "core:controls", "core:mod_settings", "core:world_rules",
    "core:resource_packs", "core:shader_packs", "core:hud_editor", "core:touch_buttons",
    "core:debug_options", "core:tags", "core:mods", "core:disabled_mods", "core:profile",
    "core:account", "core:finder", "core:achievements", "core:admission", "core:multiplayer",
    "core:chat",
    "base:video", "base:video_fantasy", "base:video_dlss", "base:video_developer", "base:map",
    "base:stats", "base:web", "base:knapping", "base:campfire", "base:charcoal_clamp",
    "base:cooking_pot", "base:crucible", "base:drying_rack", "base:forge", "base:tanning_frame",
    "base:tanning_pit", "base:tombstone",
    "animals:journal", "animals:scout", "animals:animal", "animals:animal_family",
    "animals:animal_genes", "animals:look", "packages:personal", "portals:portal",
]
KEYS = ["KeyE", "KeyR", "KeyP", "KeyL"]
FROM_TITLE = ["core:title", "core:worlds", "core:create_world", "core:multiplayer"]


def opened(lines, name):
    lines.append(f"peek {name}")


def main():
    out = [
        "# Generated by fit_gen.py: the text-fit check over every screen (run with -- --ui-audit).",
        "loaded",
        "idle",
        "wait 2",
        "chat /developer_menu on",
        "wait 0.5",
        "cursor 0.02 0.02",
    ]
    for lang in LANGS:
        out += [f"set_config core:language {lang}", "wait 1.5"]
        for s in SCALES:
            out += [f"set_config core:gui_scale {s}", "wait 1", f"# {lang} at {s or 'auto'}"]
            for name in IN_WORLD:
                opened(out, name)
            for k in KEYS:
                out += [f"key {k}", "wait 0.6", "key Escape", "wait 0.3"]
            out += ["screen core:multiplayer", "wait 0.6", "tap core:multiplayer id:links", "wait 0.8",
                    "key Escape", "wait 0.3", "tap core:multiplayer id:friends", "wait 0.8", "key Escape",
                    "wait 0.3", "key Escape", "wait 0.3"]
    out += ["leave", "wait 3"]
    for lang in LANGS:
        out += [f"set_config core:language {lang}", "wait 1.5"]
        for s in SCALES:
            out += [f"set_config core:gui_scale {s}", "wait 1", f"# title: {lang} at {s or 'auto'}"]
            for name in FROM_TITLE[1:]:
                opened(out, name)
            out += ["screen core:worlds", "wait 0.6", "tap_once core:worlds id:world:0", "wait 0.6",
                    "tap core:worlds id:new_address", "wait 0.6", "key Escape", "wait 0.3",
                    "tap core:worlds id:delete_world", "wait 0.6", "key Escape", "wait 0.3",
                    "key Escape", "wait 0.3"]
    out += ["set_config core:language en_us", "set_config core:gui_scale 2", "wait 1", "quit"]
    pathlib.Path(__file__).with_name("fit_all.txt").write_text("\n".join(out) + "\n")
    print(len(out), "lines")


if __name__ == "__main__":
    main()
