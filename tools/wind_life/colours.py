#!/usr/bin/env python3
"""Wind life's colours, from our own block textures: each leaf texture's mean colour (what a leaf
off it is, before the biome's tint), each blossom's and each flower's petal colour (its texture's
pixels that aren't stem or leaf green). Writes mods/base/src/wind_life_colours.rs.

Run from the repository root: python3 tools/wind_life/colours.py
"""
import glob
import os

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def pixels(path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    # An animated strip: its first frame.
    if h > w:
        im = im.crop((0, 0, w, w))
    return [p for p in im.get_flattened_data() if p[3] >= 128]


def mean(px):
    n = max(len(px), 1)
    return tuple(round(sum(p[i] for p in px) / n) for i in range(3))


def hexed(c):
    return "0x%02X%02X%02X" % c


def petal(px):
    """The petals: pixels neither green-dominant nor exactly grey (a bloom texture's leaves are
    grey, tinted by the biome); the brighter two thirds of them (lit petals, not the dark centre);
    all pixels if there are none."""
    green = lambda p: p[1] > p[0] * 1.08 and p[1] > p[2] * 1.08
    grey = lambda p: p[0] == p[1] == p[2]
    rest = [p for p in px if not green(p) and not grey(p)]
    if len(rest) < 3:
        return mean(px)
    rest.sort(key=lambda p: p[0] + p[1] + p[2])
    return mean(rest[len(rest) // 3:])


def main():
    leaves = {}
    blossoms = {}
    flowers = {}
    for path in sorted(glob.glob(f"{ROOT}/mods/*/assets/textures/block/*.png")):
        mod = path.split("/mods/")[1].split("/")[0]
        stem = os.path.basename(path)[:-4]
        px = pixels(path)
        if not px:
            continue
        if stem.startswith("leaves_"):
            name = stem[len("leaves_"):]
            if name.endswith("_bloom"):
                blossoms[(mod, name[: -len("_bloom")])] = petal(px)
            elif not name.endswith("_green") and not name.endswith("_overlay"):
                leaves[(mod, name)] = mean(px)
        elif os.path.exists(path[:-4] + "_green.png"):
            # A flower: its bloom look beside its green one.
            flowers[f"{mod}:{stem}"] = petal(px)
    # Dogwood's bloom is its plain texture, its green look `_green`.
    if ("base", "dogwood") in leaves:
        blossoms[("base", "dogwood")] = petal(pixels(f"{ROOT}/mods/base/assets/textures/block/leaves_dogwood.png"))
        leaves[("base", "dogwood")] = mean(pixels(f"{ROOT}/mods/base/assets/textures/block/leaves_dogwood_green.png"))
    out = [
        "//! Generated by `tools/wind_life/colours.py` from our block textures; don't edit by hand.",
        "//! Each leaf block's mean colour (before its biome's tint), each blossom's and flower's petals.",
        "",
        "/// `<mod>:<wood>_leaves` and the mean colour of its leaves.",
        f"pub const LEAVES: [(&str, u32); {len(leaves)}] = [",
    ]
    out += [f'    ("{m}:{n}_leaves", {hexed(c)}),' for (m, n), c in sorted(leaves.items())]
    out += ["];", "", "/// `<mod>:<wood>_leaves` in bloom and its petals' colour.", f"pub const BLOSSOMS: [(&str, u32); {len(blossoms)}] = ["]
    out += [f'    ("{m}:{n}_leaves", {hexed(c)}),' for (m, n), c in sorted(blossoms.items())]
    out += ["];", "", "/// Flowers (blocks with a bloom look) and their petals' colour.", f"pub const FLOWERS: [(&str, u32); {len(flowers)}] = ["]
    out += [f'    ("{n}", {hexed(c)}),' for n, c in sorted(flowers.items())]
    out += ["];", ""]
    with open(f"{ROOT}/mods/base/src/wind_life_colours.rs", "w") as f:
        f.write("\n".join(out))
    print(f"{len(leaves)} leaves, {len(blossoms)} blossoms, {len(flowers)} flowers")


if __name__ == "__main__":
    main()
