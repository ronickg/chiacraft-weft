#!/usr/bin/env python3
"""Writes mods/testkit/scripts/night_survival.txt: one night, dusk to dawn, for a same-age (Stone
Age) player against base's mobs on the curve (`vitals::mobs`).

A walled lane 3 wide and 3 high, roofed, running 24 blocks toward -z; the player stands at its
closed end facing down it with a flint spear (the Stone Age kit's weapon) and no armour (the kit's
hide clothes only warm), swinging at the spear's pace. A wave of mobs is spawned at the far end
every minute. Mob spawning is off so only the waves come. Every hit between the player and a mob,
and every death, is a `mob_fight:` line in run.log (`mods/base/src/mobs.rs`).

Run: python3 tools/progression/gen_night.py
"""
from pathlib import Path

NIGHT_SECS = 600  # 12000 ticks, dusk (12000) to dawn (24000), at 20 a second
WAVE_SECS = 60
SWING = 0.9  # a spear's 1.2 swings a second (`vitals::gear`), with a little slack for charge
FAR_Z = -22
# A wave per minute: zombies every time, a spider every other, a skeleton every third.
def wave(i):
    w = ["base:zombie", "base:zombie"]
    if i % 2 == 1:
        w.append("base:spider")
    if i % 3 == 2:
        w.append("base:skeleton")
    return w

out = []
o = out.append
o("# One night against base's mobs on the curve (generated by tools/progression/gen_night.py; edit that).")
o("# A Stone Age player (flint spear, no armour) at the closed end of a roofed 3x3 lane, facing -z;")
o("# a wave at the far end every minute, dusk to dawn. Read run.log: `mob_fight:` lines (hits both")
o("# ways, deaths), `op health` answers, `expect alive` misses (one per wave the player ended dead).")
o("# Each wave starts healed, the last wave cleared; a dead player respawns within 10 swings. Mob spawning off.")
o("loaded")
o("idle")
o("chat /rule core:mob_spawning 0")
o("chat /tk mode spectator")
o("chat /tp 0.5 206 -0.5")
o("wait 2")
o("loaded")
# Ground and the lane: solid stone, then the lane's air, walls and roof are what's left.
o("chat /tk fill -6 196 -30 6 204 4 stone")
o(f"chat /tk fill -1 200 {FAR_Z - 3} 1 202 -1 core:air")
o("chat /tk fill -6 205 -30 6 215 4 core:air")
o("wait 1")
o("chat /time set 12000")
o("chat /tk mode survival")
o("chat /tp 0.5 200 -0.5")
o("chat /gear spear flint slot=0")
o("wait 1")
o("chat /tk heal")
o("look 0 -8")
o("where night_start")
o("op health")
o("shot night_start.png")
swings = int(WAVE_SECS / SWING)
for i in range(NIGHT_SECS // WAVE_SECS):
    o(f"# ---- wave {i + 1}, {i} min into the night")
    # Each wave on its own: what's left of the last one goes (its deaths log `by 0`), and the
    # player starts it whole, back from the death screen if the last one killed them.
    for kind in ("base:zombie", "base:spider", "base:skeleton", "base:arrow"):
        o(f"chat /kill @e[type={kind}]")
    o("respawn")
    o("wait 1")
    o("chat /tp 0.5 200 -0.5")
    o("chat /gear spear flint slot=0")
    o("chat /tk heal")
    o(f"where wave_{i + 1}")
    for j, kind in enumerate(wave(i)):
        o(f"chat /tk spawn {kind} {j - 1} 200 {FAR_Z}")
    o("op health")
    for n in range(swings):
        # A death mid-wave: back up and armed again within 10 swings, not healed.
        if n and n % 10 == 0:
            o("respawn")
            o("chat /gear spear flint slot=0")
        o("chat /tp 0.5 200 -0.5")
        o("look 0 -8")
        o("press core:attack")
        o(f"wait {SWING}")
    o("expect alive")
    o(f"entities 30")
o("where night_end")
o("op health")
o("expect alive")
o("shot night_end.png")
o("quit")
path = Path(__file__).resolve().parents[2] / "mods/testkit/scripts/night_survival.txt"
path.write_text("\n".join(out) + "\n")
print(f"{path}: {len(out)} lines")
